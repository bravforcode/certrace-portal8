/* ════════════════════════════════════════════════════════════
   THE DOCUMENTS CARD GRID — categories, binding, who-to-ask

   Section 1 of the precursor/evidence spec replaces the flat checklist with
   cards grouped into five named categories. This file holds down the parts
   of that regrouping that live in the data model, not the component: every
   required key still lands in exactly one of the five categories, a
   recurring document that arrives unbound must not count as coverage, and a
   singleton document counts the moment it is reviewed because there is only
   ever one instance of it to bind to.
   ════════════════════════════════════════════════════════════ */

import { test } from "node:test";
import assert from "node:assert/strict";

class MemoryStorage {
  private map = new Map<string, string>();
  getItem(k: string) {
    return this.map.has(k) ? this.map.get(k)! : null;
  }
  setItem(k: string, v: string) {
    this.map.set(k, v);
  }
  removeItem(k: string) {
    this.map.delete(k);
  }
  clear() {
    this.map.clear();
  }
}

const g = globalThis as unknown as { window?: unknown; localStorage?: unknown };
const storage = new MemoryStorage();
g.window = { localStorage: storage };
g.localStorage = storage;

const {
  EVIDENCE_CATEGORY_ORDER,
  EVIDENCE_DEPARTMENT_LABEL,
  EVIDENCE_DEPARTMENT_WHO_TO_ASK,
  ANNUAL_REQUIRED_KEYS,
  ALL_CONDITIONAL_ANNUAL_KEYS,
  PRECURSOR_VERIFICATION_KEY,
  MILL_TEST_CERTIFICATE_KEY,
  CONTRACT_OR_PPA_KEY,
  LAB_ANALYSIS_KEY,
  isBound,
  coverageRowFor,
  annualRequiredKeys,
  annualScopeFor,
  requiredKeysForMonth,
} = await import("../workspace-evidence");
const { emptyMonth } = await import("../monthly-data");

/* ── The five categories cover every key, and only those five ─── */

test("EVIDENCE_CATEGORY_ORDER names exactly the five categories the cards render", () => {
  assert.deepEqual(EVIDENCE_CATEGORY_ORDER, ["operations", "finance", "suppliers", "lab", "organisation"]);
  for (const dept of EVIDENCE_CATEGORY_ORDER) {
    assert.ok(EVIDENCE_DEPARTMENT_LABEL[dept], `${dept} has no display label`);
    assert.ok(EVIDENCE_DEPARTMENT_WHO_TO_ASK[dept], `${dept} has no default "who to ask" line`);
  }
});

test("every fixed annual key and every conditional key lands in one of the five categories", () => {
  const all = [
    ...ANNUAL_REQUIRED_KEYS,
    PRECURSOR_VERIFICATION_KEY,
    MILL_TEST_CERTIFICATE_KEY,
      CONTRACT_OR_PPA_KEY,
    LAB_ANALYSIS_KEY,
    ...requiredKeysForMonth({ ...emptyMonth("ws-1", "2026-03"), fuels: [{ id: "f1", fuelType: "natural_gas", quantity: 1, unit: "m3", efTco2PerGj: 0.056, oxidationFactor: 1, factorSource: "eu_standard" }] }, true),
  ];
  for (const k of all) {
    assert.ok(k.department && (EVIDENCE_CATEGORY_ORDER as string[]).includes(k.department), `${k.key} is not in one of the five card categories`);
  }
});

/* ── The document sources named in the spec land in the categories it names ── */

test("category B (Accounting/Finance) holds the utility invoice, the fuel invoice and the carbon price receipt", () => {
  // utility-invoice is a genuinely per-month document (the bill for THAT
  // month) — generated by requiredKeysForMonth(), not the fixed annual list.
  const monthKeys = requiredKeysForMonth({ ...emptyMonth("ws-1", "2026-03"), fuels: [{ id: "f1", fuelType: "diesel", quantity: 1, unit: "l", efTco2PerGj: 0.074, oxidationFactor: 1, factorSource: "eu_standard" }] }, true);
  assert.equal(monthKeys.find((k) => k.key === "utility-invoice")?.department, "finance");
  assert.equal(monthKeys.find((k) => k.key === "utility-invoice")?.frequency, "monthly");
  const fuelInvoice = monthKeys.find((k) => k.key.startsWith("fuel-invoice:"));
  assert.equal(fuelInvoice?.department, "finance");
});

test("category C (Supplier documents via Smart Link) holds the precursor verification report and the mill test certificate", () => {
  assert.equal(PRECURSOR_VERIFICATION_KEY.department, "suppliers");
  assert.equal(MILL_TEST_CERTIFICATE_KEY.department, "suppliers");
});

test("the generic supplier communication template requirement was retired — the Supply Chain — Precursor Tree's per-node Documents section replaced it", () => {
  const all = [...ANNUAL_REQUIRED_KEYS, ...ALL_CONDITIONAL_ANNUAL_KEYS];
  assert.equal(all.some((k) => k.key === "supplier-communication-template"), false);
});

test("category E (Organisation-level, one-time) holds the QA record and the PPA", () => {
  assert.equal(ANNUAL_REQUIRED_KEYS.find((k) => k.key === "internal-qa-record")?.department, "organisation");
  assert.equal(CONTRACT_OR_PPA_KEY.department, "organisation");
  // The org chart and the previous verification report were retired as
  // requirements; nothing may reintroduce them by name.
  assert.equal(ANNUAL_REQUIRED_KEYS.some((k) => k.key === "org-chart"), false);
  assert.equal(ALL_CONDITIONAL_ANNUAL_KEYS.some((k) => k.key === "previous-verification-report"), false);
});

/* ── Binding gate ───────────────────────────────────────────── */

test("a recurring document with no month and no explicit bind target is uploaded but does not count", () => {
  const item = { id: "e1", workspaceId: "ws-1", fieldKeys: ["mill-test-certificate"], sourceType: "mill_test_certificate" as const, fileName: "mill.pdf", capturedAt: "2026-01-01" };
  assert.equal(isBound(item, MILL_TEST_CERTIFICATE_KEY), false);

  const row = coverageRowFor(MILL_TEST_CERTIFICATE_KEY, [item]);
  assert.equal(row.covered, false, "an unbound file must not read as coverage");
  assert.equal(row.awaitingReview, 0, "the file WAS reviewed — it is the binding that is missing");
  assert.equal(row.awaitingBinding, 1);
});

test("giving the same file a bind target is what turns the row green", () => {
  const item = {
    id: "e1",
    workspaceId: "ws-1",
    fieldKeys: ["mill-test-certificate"],
    sourceType: "mill_test_certificate" as const,
    fileName: "mill.pdf",
    capturedAt: "2026-01-01",
    boundTo: "Chonburi Foundry — March shipment",
  };
  assert.equal(isBound(item, MILL_TEST_CERTIFICATE_KEY), true);
  const row = coverageRowFor(MILL_TEST_CERTIFICATE_KEY, [item]);
  assert.equal(row.covered, true);
  assert.equal(row.awaitingBinding, 0);
});

test("a month-scoped item is already bound by its own month — no extra step for the ordinary monthly flow", () => {
  const item = { id: "e1", workspaceId: "ws-1", month: "2026-03", fieldKeys: ["production"], sourceType: "erp_export" as const, fileName: "prod.pdf", capturedAt: "2026-03-28" };
  const productionKey = requiredKeysForMonth(emptyMonth("ws-1", "2026-03"), true).find((k) => k.key === "production")!;
  assert.equal(isBound(item, productionKey), true);
  assert.equal(coverageRowFor(productionKey, [item]).covered, true);
});

test("a one-time document counts the moment it is reviewed — there is only ever one instance to bind to", () => {
  const item = { id: "e1", workspaceId: "ws-1", fieldKeys: ["internal-qa-record"], sourceType: "other" as const, fileName: "qa.pdf", capturedAt: "2026-01-01" };
  const qaKey = ANNUAL_REQUIRED_KEYS.find((k) => k.key === "internal-qa-record")!;
  assert.equal(qaKey.frequency, "one_time");
  assert.equal(isBound(item, qaKey), true);
  assert.equal(coverageRowFor(qaKey, [item]).covered, true);
});

/* ── Conditional visibility, read from the workspace rather than asked ── */

test("the contract/PPA row appears only once a PPA or direct-link electricity source is on file", () => {
  storage.clear();
  const before = annualScopeFor("ws-1", "2026-01-01", "2026-12-31", false);
  assert.equal(annualRequiredKeys(before).some((k) => k.key === "contract-or-ppa"), false);

  storage.setItem(
    "certrace:monthly-data",
    JSON.stringify({ "ws-1": [{ workspaceId: "ws-1", month: "2026-01", fuels: [], electricitySources: [{ id: "s1", sourceType: "direct_technical_link", mwh: 5, factorTco2PerMwh: 0.3 }] }] }),
  );
  const after = annualScopeFor("ws-1", "2026-01-01", "2026-12-31", false);
  assert.equal(annualRequiredKeys(after).some((k) => k.key === "contract-or-ppa"), true);
});

test("the previous verification report is never asked for, in a first year or any later one", () => {
  storage.clear();
  const firstYear = annualScopeFor("ws-1", "2026-01-01", "2026-12-31", false);
  assert.equal(annualRequiredKeys(firstYear).some((k) => k.key === "previous-verification-report"), false);

  storage.setItem(
    "certrace:workspace-mmd-versions",
    JSON.stringify({ "ws-1": [{ id: "v1", workspaceId: "ws-1", n: 1, finalisedAt: "2025-10-01", author: "a", content: {}, periodStart: "2025-01-01", periodEnd: "2025-12-31" }] }),
  );
  const laterYear = annualScopeFor("ws-1", "2026-01-01", "2026-12-31", false);
  assert.equal(annualRequiredKeys(laterYear).some((k) => k.key === "previous-verification-report"), false, "retired as a requirement");
});
