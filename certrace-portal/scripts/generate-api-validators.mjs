import { createGenerator } from "ts-json-schema-generator";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { writeFileSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
const targets = [
  ["StoredFile", "lib/api/files.ts", "./files"],
  ["Declaration", "lib/data.ts", "../data"],
  ["SupplierState", "lib/supplier-store.ts", "../supplier-store"],
  ["LinkResolution", "lib/api/links.ts", "./links"],
  ["SubmissionSummary", "lib/api/links.ts", "./links"],
  [
    "WorkspaceResolution",
    "lib/workspace-link-sync.ts",
    "../workspace-link-sync",
  ],
  [
    "WorkspaceLinkState",
    "lib/workspace-link-sync.ts",
    "../workspace-link-sync",
  ],
  ["LinkState", "lib/precursor-link-sync.ts", "../precursor-link-sync"],
  ["Resolution", "lib/precursor-link-sync.ts", "../precursor-link-sync"],
];
const ajv = new Ajv({ strict: false, code: { source: true, esm: true } });
const names = {};
for (const [type, path] of targets) {
  const schema = createGenerator({
    path: resolve(path),
    tsconfig: resolve("tsconfig.json"),
    type,
    skipTypeCheck: true,
    additionalProperties: true,
  }).createSchema(type);
  ajv.addSchema(schema, type);
  names[`is${type}`] = type;
}
const code =
  "// Generated by scripts/generate-api-validators.mjs. Do not edit.\n" +
  standaloneCode(ajv, names);
const declarations =
  targets
    .map(
      ([type, , path]) =>
        `export declare function is${type}(value: unknown): value is import('${path}').${type};`,
    )
    .join("\n") + "\n";
for (const [path, text] of [
  ["lib/api/validators.js", code],
  ["lib/api/validators.d.ts", declarations],
]) {
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== text)
      throw new Error(`${path} is stale. Run bun run api:generate.`);
  } else writeFileSync(path, text);
}
