/* Shared between /forgot-password and /reset-password, so both agree on the
   storage key without either importing the other's page.

   ── Why sessionStorage, and not the URL ───────────────────────
   /reset-password needs the address the code was sent to. The obvious way to
   carry it is `?email=…`, and it is the wrong one: a query string is written
   to browser history, to any proxy access log on the way, and to whatever the
   person pastes the link into when they ask a colleague for help. None of
   that is worth saving one field.

   sessionStorage keeps it in the tab that asked, dies with the tab, and never
   leaves the browser. It is a convenience, not a credential — the reset page
   works when it comes back empty, because the field is editable and the code
   is what actually authorises anything. */

const RESET_EMAIL_KEY = "certrace:reset-email";

/** Storage can throw outright — private windows, blocked site data. */
export function rememberResetEmail(email: string): void {
  try {
    window.sessionStorage.setItem(RESET_EMAIL_KEY, email);
  } catch {
    /* The reset page will just ask for it again. */
  }
}

export function recallResetEmail(): string {
  try {
    return window.sessionStorage.getItem(RESET_EMAIL_KEY) ?? "";
  } catch {
    return "";
  }
}

export function forgetResetEmail(): void {
  try {
    window.sessionStorage.removeItem(RESET_EMAIL_KEY);
  } catch {
    /* Nothing to clean up if it was never written. */
  }
}

/* Enough to catch "somebody@" and "somebody@company" — the two shapes that
   look finished in the box and bounce every email we send. Same expression
   /register uses; the real check is whether the code arrives. */
export const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;

/** The reset code is six digits, generated by app/core/security.py. */
export const CODE_RE = /^\d{6}$/;
