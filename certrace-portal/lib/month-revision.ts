/* ════════════════════════════════════════════════════════════
   WHAT, EXACTLY, NEEDS FIXING — and who is allowed to fix it

   `requestRevision` in lib/month-submission.ts already sends a month back with
   a note. A note is not enough. The supplier receives twenty screens of form
   and one sentence of prose, and has to work out which of the twenty the
   sentence is about — so the common outcome is that they change the figure
   they think was meant, resubmit, and the exporter asks again.

   THE UNIT OF A REVISION IS AN AREA, NOT A SENTENCE. This module names the
   places in the supplier flow a revision can be aimed at: each one carries the
   step it lives on and the DOM anchor of the control itself, which is what
   lets the supplier's own screen scroll to the first thing that needs
   attention rather than describing it.

   The list is deliberately COARSER than the quality check's findings. A
   finding is generated by a rule about a value ("the NCV on fuel 2 is
   missing"); an area is a thing a person asks another person to look at ("the
   fuels"). Asking for a revision is the second kind of statement, and one
   checkbox per generated finding would be a form of forty boxes that changes
   shape between months.

   THE EDIT REQUEST RUNS THE OTHER WAY. A submitted month is closed to the
   supplier — that is the point of submitting — but plants find their own
   mistakes, and the only alternative to a request is a phone call the portal
   never hears about. So the supplier can ask, the exporter approves or
   refuses, and an approval is what reopens the month. Nothing reopens itself.
   ════════════════════════════════════════════════════════════ */

