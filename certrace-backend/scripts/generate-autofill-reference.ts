/** Shared UI choices and configured defaults compiled into the backend, never copied by hand. */
import {
  FUEL_TYPES,
  MONTHLY_FUEL_UNITS,
} from "../../certrace-portal/lib/monthly-data";
import {
  STANDARD_MATERIALS,
  CARBON_CONTENTS,
} from "../../certrace-portal/lib/cbam/process-factors";
import { euStandardFor } from "../../certrace-portal/lib/cbam/fuel-defaults";
import { ELECTRICITY_GRID_FACTORS } from "../../certrace-portal/lib/cbam/electricity-grid-factors";
import {
  READING_FREQUENCY_OPTIONS,
  ELECTRICITY_SUPPLY_OPTIONS,
  PROCESS_OPTIONS,
  emptyMmd,
} from "../../certrace-portal/lib/workspace-mmd";
const data = {
  emptyMmd: emptyMmd("", ""),
  choices: {
    fuelType: FUEL_TYPES.map((f) => ({ value: f.id, label: f.label })),
    materialId: [
      ...STANDARD_MATERIALS.map((m) => ({ value: m.id, label: m.label })),
      ...CARBON_CONTENTS.map((m) => ({ value: m.material, label: m.label })),
    ],
    readingFrequency: READING_FREQUENCY_OPTIONS.map((f) => ({
      value: f.id,
      label: f.label,
    })),
    electricitySupply: ELECTRICITY_SUPPLY_OPTIONS.map((s) => ({
      value: s.id,
      label: s.label,
    })),
  },
  processOptions: PROCESS_OPTIONS,
  fuels: Object.fromEntries(
    FUEL_TYPES.flatMap((f) =>
      MONTHLY_FUEL_UNITS.flatMap((unit) => {
        const d = euStandardFor(f.id, unit);
        return d
          ? [
              [
                `${f.id}:${unit}`,
                {
                  ef: d.efTco2PerGj,
                  ncv: d.ncvMjPerUnit,
                  citation: d.citation,
                },
              ],
            ]
          : [];
      }),
    ),
  ),
  grids: ELECTRICITY_GRID_FACTORS,
};
const text = `// Generated by scripts/generate-autofill-reference.ts. Do not edit.\nexport const autofillReference = ${JSON.stringify(data, null, 2)};\n`;
const file = new URL(
  "../src/modules/evidence/autofill-reference.ts",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if ((await Bun.file(file).text()) !== text)
    throw Error(
      "Autofill reference data is stale; run bun scripts/generate-autofill-reference.ts",
    );
} else await Bun.write(file, text);
